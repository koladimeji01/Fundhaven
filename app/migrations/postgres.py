"""Initialize the PostgreSQL equivalent of BudgetWise SQLite schema v8.

This creates only missing tables and indexes. It NEVER deletes existing data.
SQLite migration history (versions 1-8) remains in manager.py, while the
PostgreSQL schema starts at logical version 8.

Running the backend with DATABASE_URL switches to PostgreSQL. Existing SQLite
records are NOT automatically copied; use app/migrations/sqlite_to_postgres.py
after reviewing the migration guide and making a backup.
"""
from app.db_backend import get_database_url
from app.logging_config import logger


SCHEMA_STATEMENTS = [
    """
    CREATE TABLE IF NOT EXISTS migrations (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        version INTEGER NOT NULL UNIQUE,
        description TEXT NOT NULL,
        applied_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
    )
    """,
    """
    CREATE TABLE IF NOT EXISTS users (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        name TEXT NOT NULL UNIQUE,
        income NUMERIC(18, 2) NOT NULL CHECK (income > 0),
        password TEXT NOT NULL,
        email TEXT,
        monthly_reports_enabled INTEGER NOT NULL DEFAULT 0
            CHECK (monthly_reports_enabled IN (0, 1))
    )
    """,
    """
    CREATE UNIQUE INDEX IF NOT EXISTS idx_users_email
    ON users (email) WHERE email IS NOT NULL
    """,
    """
    CREATE TABLE IF NOT EXISTS expenses (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
        amount NUMERIC(18, 2) NOT NULL CHECK (amount > 0),
        category TEXT NOT NULL,
        description TEXT NOT NULL,
        date TEXT NOT NULL
    )
    """,
    "CREATE INDEX IF NOT EXISTS idx_expenses_user_id ON expenses(user_id)",
    "CREATE INDEX IF NOT EXISTS idx_expenses_date ON expenses(date)",
    "CREATE INDEX IF NOT EXISTS idx_expenses_user_date ON expenses(user_id, date DESC)",
    """
    CREATE TABLE IF NOT EXISTS budgets (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
        category TEXT NOT NULL,
        amount NUMERIC(18, 2) NOT NULL CHECK (amount > 0),
        created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
        updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
    )
    """,
    "CREATE INDEX IF NOT EXISTS idx_budgets_user_id ON budgets(user_id)",
    """
    CREATE TABLE IF NOT EXISTS goals (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
        name TEXT NOT NULL,
        target_amount NUMERIC(18, 2) NOT NULL CHECK (target_amount > 0),
        current_amount NUMERIC(18, 2) NOT NULL DEFAULT 0
            CHECK (current_amount >= 0),
        target_date TEXT,
        created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
        updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
    )
    """,
    "CREATE INDEX IF NOT EXISTS idx_goals_user_id ON goals(user_id)",
    """
    CREATE TABLE IF NOT EXISTS monthly_income (
        user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
        month TEXT NOT NULL,
        amount NUMERIC(18, 2) NOT NULL CHECK (amount > 0),
        PRIMARY KEY (user_id, month)
    )
    """,
    """
    CREATE TABLE IF NOT EXISTS login_challenges (
        id TEXT PRIMARY KEY,
        user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
        code_digest TEXT NOT NULL,
        created_at BIGINT NOT NULL,
        expires_at BIGINT NOT NULL,
        last_sent_at BIGINT NOT NULL,
        attempts INTEGER NOT NULL DEFAULT 0,
        resend_count INTEGER NOT NULL DEFAULT 0,
        consumed_at BIGINT
    )
    """,
    """
    CREATE INDEX IF NOT EXISTS idx_login_challenges_user
    ON login_challenges(user_id, created_at)
    """,
    """
    CREATE TABLE IF NOT EXISTS monthly_report_delivery (
        user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
        report_month TEXT NOT NULL,
        status TEXT NOT NULL CHECK (
            status IN ('sending', 'sent', 'failed')
        ),
        claimed_at BIGINT NOT NULL,
        sent_at BIGINT,
        provider_message_id TEXT,
        PRIMARY KEY (user_id, report_month)
    )
    """,
]


def run_postgres_migrations():
    url = get_database_url()
    if not url:
        raise RuntimeError("Set DATABASE_URL to enable PostgreSQL")

    try:
        import psycopg
    except ImportError as exc:
        raise RuntimeError(
            "Install psycopg before enabling PostgreSQL: "
            "pip install 'psycopg[binary]'"
        ) from exc

    with psycopg.connect(url, connect_timeout=10) as conn:
        with conn.cursor() as cur:
            # Prevent concurrent application workers from racing through DDL.
            cur.execute("SELECT pg_advisory_xact_lock(82564202)")
            for statement in SCHEMA_STATEMENTS:
                cur.execute(statement)
            cur.execute("""
                INSERT INTO migrations(version, description)
                VALUES (8, 'PostgreSQL schema equivalent to SQLite version 8')
                ON CONFLICT(version) DO NOTHING
            """)
        conn.commit()

    logger.info("BudgetWise PostgreSQL schema checked (version 8)")
