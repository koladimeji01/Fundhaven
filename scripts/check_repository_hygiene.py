"""Fail CI when Git tracks private or generated local artifacts.

This checks file names only. It will not display or parse database/secret contents.
Git history remediation is a separate coordinated operation.
"""
from __future__ import annotations

import subprocess
import sys
from pathlib import PurePosixPath

PRIVATE_DIRECTORIES = frozenset({
    "venv", ".venv", "node_modules", "__pycache__", ".pytest_cache", ".mypy_cache",
    ".ruff_cache", ".vercel", "dist", ".tox",
})
PRIVATE_EXTENSIONS = frozenset({
    ".db", ".sqlite", ".sqlite3", ".pyc", ".pyo", ".p12", ".pfx", ".pem", ".key",
})
PRIVATE_FILENAMES = frozenset({
    "budget_data.json", "credentials.json", "id_rsa", "id_ed25519",
    "api_backup.py",
})


def classify_path(path: str) -> str | None:
    """Return a short reason if a path should never be tracked by Git."""
    path = path.replace("\\", "/").strip("/")
    if not path:
        return None
    segments = PurePosixPath(path).parts
    name = segments[-1].lower()
    if name == ".env.example":
        return None
    if any(segment.lower() in PRIVATE_DIRECTORIES for segment in segments[:-1]):
        return "generated or private directory"
    if name == ".env" or name.startswith(".env."):
        return "environment secrets file"
    if name in PRIVATE_FILENAMES:
        return "potential private data or obsolete backup"
    if PurePosixPath(name).suffix.lower() in PRIVATE_EXTENSIONS:
        return "private data, credentials, or generated bytecode"
    if name.startswith("budgetwise_backup") or name.endswith(".db-wal") or name.endswith(".db-shm"):
        return "database backup or journal"
    return None


def tracked_paths() -> list[str]:
    result = subprocess.run(
        ["git", "ls-files", "-z"], capture_output=True, check=True
    )
    return [
        item.decode("utf-8", errors="replace")
        for item in result.stdout.split(b"\x00")
        if item
    ]


def main() -> int:
    blocked = [(path, classify_path(path)) for path in tracked_paths()]
    blocked = [(path, reason) for path, reason in blocked if reason]
    if blocked:
        print("ERROR: Private/generated files must not be Git-tracked:")
        for path, reason in blocked:
            print(f" - {path}: {reason}")
        print("Remove these files from Git's index and rotate exposed credentials.")
        return 1
    print("Repository hygiene: tracked paths contain no blocked private/runtime files.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
